#!/usr/bin/env node
/**
 * OUM pixel edge system — frame generator (SINGLE SOURCE OF TRUTH).
 *
 * Emits `app/px-frames.generated.css`:
 *   - the --px token + edge colour tokens (one global pixel size, integer px)
 *   - SVG border-image tiles: solid stair-corner frames, pixel-dash frames,
 *     side-only variants (dividers), and two-tone "duo" frames for
 *     unpredictable backgrounds.
 *   - surface→colour mapping selectors (smart colour rule).
 *
 * Mechanism notes
 *   - Frames are painted through `border-image` inside the element's own
 *     border area: element size and layout never change.
 *   - Because the frame belongs to the element it decorates, every transform,
 *     transition and animation moves it in perfect sync (no pseudo-element
 *     overlays, no lag, no ghost edges).
 *   - Tiles are vector SVGs with shape-rendering=crispEdges: every step is an
 *     integer number of CSS px, so they stay sharp at DPR 1 / 2 / 3.
 *   - Transparent slices never paint, so side-only tiles cover the divider
 *     cases (hr / table lines / separators) without touching other sides.
 *
 * Usage: node scripts/pixel/gen-frames.mjs
 */
import fs from "node:fs";
import path from "node:path";

const OUT = process.argv[2] ?? path.resolve("app/px-frames.generated.css");

/* ------------------------------------------------------------------ *
 * Tokens — THE palette. Every value is verified by check-contrast.mjs
 * to hold >= 3:1 against the surfaces it is allowed to touch.
 * ------------------------------------------------------------------ */
const TOKENS = {
  ink: "#1B1915", // default edge on light cream surfaces
  light: "#F1EBDB", // edge on ink/dark surfaces
  red: "#C0392B", // error edges (light + dark safe)
  green: "#3F7A3F", // success/selected edges (light + dark safe)
  gold: "#9C6917", // accent edges + focus ring (light + dark safe)
};

/* Side sets: t/b/l/r = one side, y = top+bottom, x = left+right, br = bottom+right */
const SIDE_SETS = {
  t: ["t"],
  b: ["b"],
  l: ["l"],
  r: ["r"],
  y: ["t", "b"],
  x: ["l", "r"],
  br: ["b", "r"],
};

/* ------------------------------------------------------------------ *
 * SVG builders. 12x12 solid tiles / 16x16 dash tiles, slice = 4px.
 * Corner = 4px staircase (2px steps): reads as 8-bit at the 4px token.
 * ------------------------------------------------------------------ */
const R = (x, y, w, h, fill) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${fill}"/>`;

const uri = (size, rects) =>
  `url('data:image/svg+xml;utf8,${encodeURIComponent(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" shape-rendering="crispEdges">${rects.join("")}</svg>`,
  )}')`;

/* staircase corners for an S x S tile, slice 4 */
const stairs = (S, c) => [
  R(2, 0, 2, 2, c), R(0, 2, 4, 2, c), // TL
  R(S - 4, 0, 2, 2, c), R(S - 4, 2, 4, 2, c), // TR
  R(0, S - 4, 4, 2, c), R(2, S - 2, 2, 2, c), // BL
  R(S - 4, S - 4, 4, 2, c), R(S - 4, S - 2, 2, 2, c), // BR
];

/* middle slices (edge thickness 4px). Dash tiles fill the first half of the
   8px middle → 4px dash + 4px gap per tile with border-image-repeat: repeat. */
const mid = (S, c) => ({
  t: R(4, 0, 4, 4, c),
  b: R(4, S - 4, 4, 4, c),
  l: R(0, 4, 4, 4, c),
  r: R(S - 4, 4, 4, 4, c),
});

const solidFull = (c) => uri(12, [...Object.values(mid(12, c)), ...stairs(12, c)]);
const dashFull = (c) => uri(16, [...Object.values(mid(16, c)), ...stairs(16, c)]);
const solidSide = (c, sides) => uri(12, sides.map((s) => mid(12, c)[s]));
const dashSide = (c, sides) => uri(16, sides.map((s) => mid(16, c)[s]));

/* two-tone stair frame: outer 2px band `outer`, inner 2px band `inner`.
   Visible against BOTH neighbouring surfaces whatever they are. */
const duoStair = (outer, inner) =>
  uri(12, [
    ...Object.values(mid(12, outer)),
    ...stairs(12, outer),
    R(4, 2, 4, 2, inner), R(4, 10, 4, 2, inner), R(2, 4, 2, 4, inner), R(10, 4, 2, 4, inner),
    R(2, 2, 2, 2, inner), R(8, 2, 2, 2, inner), R(2, 8, 2, 2, inner), R(8, 8, 2, 2, inner),
  ]);

/* 3-band frame with cut corners (for clipped silhouettes over unpredictable
   content, e.g. the video modal): light / ink / light — always visible. */
const triCut = (outer, band, inner) =>
  uri(12, [
    R(4, 0, 4, 1, outer), R(4, 1, 4, 2, band), R(4, 3, 4, 1, inner),
    R(4, 8, 4, 1, inner), R(4, 9, 4, 2, band), R(4, 11, 4, 1, outer),
    R(0, 4, 1, 4, outer), R(1, 4, 2, 4, band), R(3, 4, 1, 4, inner),
    R(8, 4, 1, 4, inner), R(9, 4, 2, 4, band), R(11, 4, 1, 4, outer),
  ]);

/* ------------------------------------------------------------------ *
 * Emit CSS
 * ------------------------------------------------------------------ */
const lines = [];
lines.push("/* AUTO-GENERATED by scripts/pixel/gen-frames.mjs — DO NOT EDIT BY HAND.");
lines.push("   Regenerate: node scripts/pixel/gen-frames.mjs */");
lines.push("");
lines.push(":root {");
lines.push("  /* THE global pixel token: corner steps, frame thickness, dash length. */");
lines.push("  --px: 4px;");
lines.push("");
lines.push("  /* Edge colour tokens (contrast-verified — scripts/pixel/check-contrast.mjs) */");
for (const [k, v] of Object.entries(TOKENS)) lines.push(`  --px-${k}: ${v};`);
lines.push("");
for (const [k, v] of Object.entries(TOKENS)) {
  lines.push(`  --px-frame-${k}: ${solidFull(v)};`);
  lines.push(`  --px-frame-${k}-d: ${dashFull(v)};`);
  for (const [set, sides] of Object.entries(SIDE_SETS)) {
    lines.push(`  --px-frame-${k}-s${set}: ${solidSide(v, sides)};`);
    lines.push(`  --px-frame-${k}-d${set}: ${dashSide(v, sides)};`);
  }
  lines.push("");
}
lines.push(`  /* two-tone stair frame: outer ${TOKENS.ink} + inner ${TOKENS.light} */`);
lines.push(`  --px-frame-duo: ${duoStair(TOKENS.ink, TOKENS.light)};`);
lines.push(`  /* two-tone cut frame for clipped silhouettes (light / ink / light) */`);
lines.push(`  --px-frame-cut: ${triCut(TOKENS.light, TOKENS.ink, TOKENS.light)};`);
lines.push("");
lines.push("  /* acting defaults: ink on cream — every bordered element, unless a");
lines.push("     mapping group below resolves a different edge colour */");
{
  const vars = [`--px-frame: var(--px-frame-ink);`, `--px-frame-d: var(--px-frame-ink-d);`];
  for (const set of Object.keys(SIDE_SETS)) {
    vars.push(`--px-frame-s${set}: var(--px-frame-ink-s${set});`);
    vars.push(`--px-frame-d${set}: var(--px-frame-ink-d${set});`);
  }
  for (const v of vars) lines.push(`  ${v}`);
}
lines.push("}");
lines.push("");

/* Colour mapping — which Tailwind border classes resolve to which edge colour.
   The first group is also the default for every bordered element (ink on cream).
   Prefixed state utilities (hover:/focus:) are excluded from the base groups
   and re-mapped to the same colour when the state is active. */
const GROUPS = {
  ink: [
    '[class*="border-"]',
    '[class~="border"]',
    '[class*="border-line"]',
    '[class*="border-ink"]',
    '[class*="border-blue"]',
    '[class*="border-indigo"]',
  ],
  light: ['[class*="border-white"]', '[class*="border-paper/"]'],
  red: ['[class*="border-red"]'],
  green: ['[class*="border-green"]', '[class*="border-emerald"]'],
  gold: ['[class*="border-gold"]', '[class*="border-amber"]'],
};

const PREFIXES = ["hover", "focus", "focus-visible", "group-hover", "sm", "md", "lg", "xl", "2xl"];

const varSet = (k) => {
  const vars = [`--px-frame: var(--px-frame-${k});`, `--px-frame-d: var(--px-frame-${k}-d);`];
  for (const set of Object.keys(SIDE_SETS)) {
    vars.push(`--px-frame-s${set}: var(--px-frame-${k}-s${set});`);
    vars.push(`--px-frame-d${set}: var(--px-frame-${k}-d${set});`);
  }
  return vars;
};

/* default group first, then colours so later colours win over the default */
for (const k of Object.keys(GROUPS)) {
  const plain = GROUPS[k].map((sel) => {
    const m = sel.match(/^\[class\*="(.+)"\]$/);
    if (!m) return sel; // [class~="border"]
    return (
      sel +
      PREFIXES.map((p) => `:not([class*="${p}:${m[1]}"])`).join("")
    );
  });
  lines.push(`${plain.join(", ")} {`);
  for (const v of varSet(k)) lines.push(`  ${v}`);
  lines.push("}");
  lines.push("");
}

/* state utilities: hover:/focus: borders take effect when the state is active */
const stateRules = [];
for (const k of Object.keys(GROUPS)) {
  const sels = [];
  for (const base of GROUPS[k]) {
    const m = base.match(/^\[class\*="(.+)"\]$/);
    if (!m) continue;
    for (const p of ["hover", "focus", "focus-visible", "group-hover"]) {
      const pseudo = p === "hover" ? ":hover" : p === "focus" || p === "focus-visible" ? ":focus" : ":is(:hover, :focus-within)";
      sels.push(`[class*="${p}:${m[1]}"]${pseudo}`);
    }
  }
  if (sels.length) stateRules.push({ k, sels });
}
for (const { k, sels } of stateRules) {
  lines.push(`${sels.join(", ")} {`);
  for (const v of varSet(k)) lines.push(`  ${v}`);
  lines.push("}");
  lines.push("");
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join("\n"));
const kb = (fs.statSync(OUT).size / 1024).toFixed(1);
console.log(`wrote ${OUT} (${kb} KB)`);
